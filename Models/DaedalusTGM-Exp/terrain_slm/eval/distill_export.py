"""Write a distillation fit's parameters into the game: the FITTED block of DistilledShape.java.

    python -m terrain_slm.eval.distill_export /mnt/extrastorage/terrain-slm-data/distill/fit_v2/best.json

Replaces the text between `// BEGIN FITTED` and `// END FITTED` in
stonebreak-game/.../heightmap/DistilledShape.java with a `new Params(...)` built from the json, in the
record's field order (distill_fit.Params field names, camelCased). The valley exponent is written
snapped, as both the fit (PORT_SAFE) and the game evaluate it.
"""
from __future__ import annotations

import argparse
import json
import re
from dataclasses import fields
from pathlib import Path

from terrain_slm.eval.distill_fit import Params
from terrain_slm.paths import MODELS_DIR

JAVA = MODELS_DIR.parent / "stonebreak-game/src/main/java/com/stonebreak/world/generation/heightmap/DistilledShape.java"


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(w[:1].upper() + w[1:] for w in rest)


def main(argv=None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("best_json")
    ap.add_argument("--java", default=str(JAVA))
    args = ap.parse_args(argv)
    p = Params(**json.loads(Path(args.best_json).read_text()))
    vals = {f.name: getattr(p, f.name) for f in fields(Params)}
    vals["valley_power"] = min((0.5, 1.0, 1.5, 2.0), key=lambda c: abs(c - vals["valley_power"]))

    java = Path(args.java)
    src = java.read_text()
    record = re.search(r"public record Params\((.*?)\)\s*\{", src, re.S).group(1)
    order = re.findall(r"double (\w+)", record)
    by_camel = {camel(k): v for k, v in vals.items()}
    missing = [o for o in order if o not in by_camel]
    if missing:
        raise SystemExit(f"Params fields missing from the fit: {missing}")
    lines, row = [], []
    for name in order:
        row.append(repr(float(by_camel[name])))
        if len(row) == 5:
            lines.append(", ".join(row))
            row = []
    if row:
        lines.append(", ".join(row))
    body = (f"    // BEGIN FITTED (generated by terrain_slm.eval.distill_export from {Path(args.best_json).parent.name}/"
            f"{Path(args.best_json).name})\n"
            "    public static final Params FITTED = new Params(\n        "
            + ",\n        ".join(lines) + ");\n    // END FITTED")
    new, n = re.subn(r"    // BEGIN FITTED.*?// END FITTED", lambda _: body, src, flags=re.S)
    if n != 1:
        raise SystemExit("FITTED markers not found exactly once")
    java.write_text(new)
    print(f"wrote {len(order)} params into {java}")


if __name__ == "__main__":
    main()
