"""Write a distillation fit's parameters into the game.

    python -m terrain_slm.eval.distill_export /mnt/extrastorage/terrain-slm-data/distill/fit_v2/best.json
    python -m terrain_slm.eval.distill_export --version 2 /mnt/extrastorage/terrain-slm-data/distill/sd/fit_v2b/best.json

Version 1 (the 2026-11-01 shape): replaces the text between `// BEGIN FITTED` and `// END FITTED` in
stonebreak-game/.../heightmap/DistilledShape.java with a `new Params(...)` of the record's first 34 fields.

Version 2 (Standard shape 2, 2026-11-19, distilled from DaedalusTGM-Exp-2): replaces `// BEGIN FITTED_V2` ..
`// END FITTED_V2` in DistilledShape.java (all fields) AND in the native generator's shape.cpp (`constexpr ShapeParams
P2 = {...}`, same field order), so Java previews and native worlds read one set of numbers.

Fields go in the Java record's order (distill_fit.Params names, camelCased). The valley exponent is written snapped,
as both the fit (PORT_SAFE) and the game evaluate it.
"""
from __future__ import annotations

import argparse
import json
import re
from dataclasses import fields
from pathlib import Path

from terrain_slm.eval.distill_fit import Params
from terrain_slm.paths import MODELS_DIR

JAVA = MODELS_DIR.parent / "stonebreak-game/src/main/java/com/stonebreak/world/generation/heightmap/DistilledShape.java"
NATIVE = MODELS_DIR.parent / "stonebreak-game/native/src/shape.cpp"
V1_FIELDS = 34


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(w[:1].upper() + w[1:] for w in rest)


def values_in_order(p: Params, order: list[str]) -> list[str]:
    vals = {f.name: getattr(p, f.name) for f in fields(Params)}
    vals["valley_power"] = min((0.5, 1.0, 1.5, 2.0), key=lambda c: abs(c - vals["valley_power"]))
    by_camel = {camel(k): v for k, v in vals.items()}
    missing = [o for o in order if o not in by_camel]
    if missing:
        raise SystemExit(f"Params fields missing from the fit: {missing}")
    return [repr(float(by_camel[name])) for name in order]


def rows(values: list[str], per: int = 5) -> list[str]:
    return [", ".join(values[i:i + per]) for i in range(0, len(values), per)]


def main(argv=None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("best_json")
    ap.add_argument("--version", type=int, default=1)
    ap.add_argument("--java", default=str(JAVA))
    ap.add_argument("--native", default=str(NATIVE))
    args = ap.parse_args(argv)
    p = Params(**json.loads(Path(args.best_json).read_text()))
    src_name = f"{Path(args.best_json).parent.name}/{Path(args.best_json).name}"

    java = Path(args.java)
    src = java.read_text()
    record = re.search(r"public record Params\((.*?)\)\s*\{", src, re.S).group(1)
    order = re.findall(r"double (\w+)", record)
    if args.version < 2:
        order = order[:V1_FIELDS]
        lines = rows(values_in_order(p, order))
        body = (f"    // BEGIN FITTED (generated by terrain_slm.eval.distill_export from {src_name})\n"
                "    public static final Params FITTED = new Params(\n        "
                + ",\n        ".join(lines) + ");\n    // END FITTED")
        new, n = re.subn(r"    // BEGIN FITTED \(.*?// END FITTED(?!_)", lambda _: body, src, flags=re.S)
        if n != 1:
            raise SystemExit("FITTED markers not found exactly once")
        java.write_text(new)
        print(f"wrote {len(order)} params into {java}")
        return

    if p.shape_version < 2:
        raise SystemExit("--version 2 needs a shape_version 2 fit")
    values = values_in_order(p, order)
    body = (f"    // BEGIN FITTED_V2 (generated by terrain_slm.eval.distill_export from {src_name})\n"
            "    public static final Params FITTED_V2 = new Params(\n        "
            + ",\n        ".join(rows(values)) + ");\n    // END FITTED_V2")
    new, n = re.subn(r"    // BEGIN FITTED_V2.*?// END FITTED_V2", lambda _: body, src, flags=re.S)
    if n != 1:
        raise SystemExit("FITTED_V2 markers not found exactly once in DistilledShape.java")
    java.write_text(new)

    native = Path(args.native)
    nsrc = native.read_text()
    struct = re.search(r"struct ShapeParams \{(.*?)\};", nsrc, re.S).group(1)
    norder = re.findall(r"(\w+)[,;]", re.sub(r"/\*.*?\*/", "", struct, flags=re.S))
    if norder != order:
        raise SystemExit(f"shape.cpp ShapeParams fields differ from the Java record:\n{norder}\n{order}")
    nbody = (f"// BEGIN FITTED_V2 (generated by terrain_slm.eval.distill_export from {src_name})\n"
             "constexpr ShapeParams P2 = {\n    " + ",\n    ".join(rows(values)) + "};\n// END FITTED_V2")
    nnew, n = re.subn(r"// BEGIN FITTED_V2.*?// END FITTED_V2", lambda _: nbody, nsrc, flags=re.S)
    if n != 1:
        raise SystemExit("FITTED_V2 markers not found exactly once in shape.cpp")
    native.write_text(nnew)
    print(f"wrote {len(order)} params into {java} and {native}")


if __name__ == "__main__":
    main()
